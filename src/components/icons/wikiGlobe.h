inline bool ink(int x,int y,int size) {
  const float r=(size-5)/2.0f, dx=x-(size-1)/2.0f, dy=y-(size-1)/2.0f;
  if (r<=0) return false;
  const float stroke=(size>32 ? size/32.0f : 1.0f)*0.8f;
  const float d=std::sqrt(dx*dx+dy*dy);
  if (std::fabs(d-r)<=stroke) return true;
  if (d>r) return false;
  const float ellipse=dx*dx/(r*r*0.25f)+dy*dy/(r*r);
  return std::fabs(ellipse-1)<stroke*2/r || std::fabs(dy)<stroke || std::fabs(std::fabs(dy)-r*0.48f)<stroke;
}
template <class Renderer>
void draw(const Renderer& renderer,int x,int y,int size,bool black=true) {
  for (int row=0;row<size;++row) for (int col=0;col<size;++col)
    if (ink(col,row,size)) renderer.drawPixel(x+col,y+row,black);
}
